-- Apply after 004_refresh_sessions.sql. Does not delete or rewrite existing records.
BEGIN;

ALTER TABLE products ADD COLUMN IF NOT EXISTS function_source_review_required boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS product_function_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prdlst_report_no varchar(255) NOT NULL REFERENCES products (prdlst_report_no),
    previous_source text,
    current_source text,
    detected_at timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_product_function_changes_product_date
    ON product_function_changes (prdlst_report_no, detected_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS product_change_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    change_id bigint NOT NULL REFERENCES product_function_changes (id),
    read_at timestamp(6),
    CONSTRAINT uq_product_notification_user_change UNIQUE (user_id, change_id)
);
CREATE INDEX IF NOT EXISTS ix_product_change_notifications_user
    ON product_change_notifications (user_id, id DESC);

ALTER TABLE inspection_records ADD COLUMN IF NOT EXISTS previous_inspection_id bigint
    REFERENCES inspection_records (id);
CREATE INDEX IF NOT EXISTS ix_inspection_records_previous
    ON inspection_records (previous_inspection_id);

COMMIT;
