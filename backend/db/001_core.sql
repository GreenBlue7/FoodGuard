-- Apply once to an empty PostgreSQL database before starting the Spring app.
-- Historical inspection values are snapshots; a product update does not rewrite them.
CREATE TABLE products (
    prdlst_report_no varchar(255) PRIMARY KEY,
    prdlst_nm varchar(255) NOT NULL,
    bssh_nm varchar(255),
    primary_fnclty text,
    product_type varchar(255) NOT NULL
);

CREATE TABLE product_approved_functions (
    prdlst_report_no varchar(255) NOT NULL,
    position integer NOT NULL,
    function_text text NOT NULL,
    PRIMARY KEY (prdlst_report_no, position),
    CONSTRAINT fk_approved_function_product
        FOREIGN KEY (prdlst_report_no) REFERENCES products (prdlst_report_no)
);

CREATE TABLE inspection_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prdlst_report_no varchar(255),
    prdlst_nm varchar(255),
    bssh_nm varchar(255),
    product_type varchar(255),
    primary_fnclty text,
    ad_text text NOT NULL,
    status varchar(255) NOT NULL,
    result_json text NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT fk_inspection_product
        FOREIGN KEY (prdlst_report_no) REFERENCES products (prdlst_report_no)
);

CREATE INDEX ix_inspection_records_created_at ON inspection_records (created_at DESC);
