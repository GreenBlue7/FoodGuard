-- Adds user accounts and ties every inspection record to its owner.
-- Apply after 001_core.sql (new database) or upgrade_existing_capstone.sql
-- (existing capstone_db). Safe to re-run.
-- inspection_records must be empty: the NOT NULL user_id has no value for
-- rows saved before accounts existed, so the ALTER fails instead of guessing.
CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    company_name varchar(100),
    role varchar(20) NOT NULL DEFAULT 'USER',
    created_at timestamp(6) NOT NULL,
    -- Emails are stored trimmed and lowercased, so "A@x.com" and "a@x.com"
    -- are one account and a plain equality lookup can use the unique index.
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_normalized CHECK (email = lower(btrim(email))),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

-- Deleting a user deletes all of that user's inspection records.
ALTER TABLE inspection_records
    ADD COLUMN IF NOT EXISTS user_id bigint NOT NULL
        CONSTRAINT fk_inspection_user REFERENCES users (id) ON DELETE CASCADE;

-- Serves the per-user history query and the cascade delete lookup.
CREATE INDEX IF NOT EXISTS ix_inspection_records_user_created_at
    ON inspection_records (user_id, created_at DESC);
